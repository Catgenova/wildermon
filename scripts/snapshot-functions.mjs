#!/usr/bin/env node
/**
 * Every function in schemas public and private, as the built database has it,
 * one file each: supabase/functions/<schema>.<name>.sql, or <name>__1.sql,
 * <name>__2.sql... for overloads (in order of their arguments).
 *
 * A function's code is the last migration that wrote it, and many are patched
 * as text by later migrations, so no migration shows what runs. These files
 * do. Generated, never edited: change a migration and run this again.
 *
 *   PGDATABASE=snap bash supabase/test/run.sh && PGDATABASE=snap node scripts/snapshot-functions.mjs
 *
 * Talks to whatever Postgres the PG* environment names (psql must be on the
 * path). Files of functions that are gone are deleted.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'supabase/functions');

// Fixed settings, so that what pg_get_functiondef deparses (names qualified
// off the search path, constants in defaults) is the same on every machine.
const SQL = `
set search_path = public;
set extra_float_digits = 1;
set datestyle = 'ISO, MDY';
set intervalstyle = postgres;
set timezone = 'UTC';
select coalesce(json_agg(json_build_object(
  'schema', n.nspname, 'name', p.proname,
  'args', pg_get_function_identity_arguments(p.oid),
  'def', pg_get_functiondef(p.oid))), '[]')
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname in ('public', 'private') and p.prokind in ('f', 'p')
  and not exists (select from pg_depend d
                  where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e');
`;

const psql = spawnSync('psql', ['-X', '-q', '-A', '-t', '-v', 'ON_ERROR_STOP=1', '-c', SQL.replace(/\n/g, ' ')], {
  encoding: 'utf8', maxBuffer: 1 << 30,
});
if (psql.status !== 0) {
  process.stderr.write(psql.stderr);
  process.exit(1);
}
const rows = JSON.parse(psql.stdout.trim().split('\n').pop());
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
rows.sort((a, b) => cmp(a.schema, b.schema) || cmp(a.name, b.name) || cmp(a.args, b.args));

const count = new Map();
for (const r of rows) count.set(`${r.schema}.${r.name}`, (count.get(`${r.schema}.${r.name}`) ?? 0) + 1);
const seen = new Map();
const files = new Map();
for (const r of rows) {
  const key = `${r.schema}.${r.name}`;
  const n = (seen.get(key) ?? 0) + 1;
  seen.set(key, n);
  const name = count.get(key) > 1 ? `${key}__${n}.sql` : `${key}.sql`;
  const body = r.def.replace(/\r\n?/g, '\n').replace(/\s+$/, '');
  files.set(name, `-- ${key}(${r.args})\n-- Generated by scripts/snapshot-functions.mjs from the migrations. Do not edit.\n${body}\n`);
}

mkdirSync(DIR, { recursive: true });
let removed = 0;
for (const f of readdirSync(DIR)) {
  if (!files.has(f)) {
    rmSync(join(DIR, f));
    removed++;
  }
}
for (const [f, text] of files) writeFileSync(join(DIR, f), text);
console.log(`${files.size} functions written to supabase/functions${removed ? `, ${removed} stale files removed` : ''}`);
