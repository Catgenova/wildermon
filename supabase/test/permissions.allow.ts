/**
 * What a browser's two roles may do, written down by hand: the list `permissions.ts` holds the island to.
 *
 * A new table, view or door fails that test until it is written down here, so that who may read it, and who may
 * call it, is a decision somebody made rather than whatever the defaults handed out. Writing is not on the list:
 * neither role may insert, update, delete or truncate anything in public, ever (the doors write as their owner).
 *
 * `TABLES`, every table and view in public, and what each role reads of it:
 *   * `'rules'`: every row, to anon and authenticated alike: the rulebook (what the browser's own definitions say,
 *     generated), and `home` (which island the keeper keeps), `keeper` (when it last swept) and `tick_time` (how
 *     long the clock took), which `private.lock_doors()` opens as it opens every table with no island on it;
 *   * `'none'`: no row to either: no SELECT, or row level security with no policy that names them;
 *   * `'view'`: a security_invoker view, read on the terms of the tables under it;
 *   * `{ authenticated: '<terms>' }`: somebody signed in reads the rows of these terms, word for word as Postgres
 *     prints the policy back (and only the columns named, where it is granted column by column); anon reads
 *     nothing. `world` is one of these: the islands you are on, and the front door's (`home`).
 *
 * `EXECUTE`, every function in public and private each role may execute: the `rpc_*` doors, and in private the
 * three a policy calls (`on_island`, `my_islands`, `hears`). anon may ask whether a name is free and nothing else.
 *
 * `SCHEMA_USAGE` and `REALTIME_POLICIES`: who may name a schema of the island's, and who hears an island's
 * broadcast channel (`private.hears`).
 */
export type Read = 'rules' | 'none' | 'view' | { anon?: string; authenticated?: string };

